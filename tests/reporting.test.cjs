const assert = require('node:assert/strict')
const { test } = require('node:test')
const app = require('./load-app.cjs')()
const report = app('src/lib/reporting.ts')
const invoice = (extra = {}) => ({ id:'i', invoice_number:'QA', status:'SENT', currency:'USD', issue_date:'2025-12-31', total:100, payments:[], ...extra })
test('cash reports actual unreversed receipts in payment year, never legacy paid status', () => {
  const rows = [invoice({payments:[{id:'p1',paid_on:'2025-12-31',amount:20},{id:'p2',paid_on:'2026-01-01',amount:30},{id:'p3',paid_on:'2026-01-02',amount:50,reversal:{id:'r'}}]}),invoice({id:'legacy',status:'PAID'}),invoice({id:'eur',currency:'EUR',payments:[{paid_on:'2026-01-01',amount:500}]})]
  assert.equal(report.sumMoney(report.incomeRecords(rows,2026,'USD','cash')),30)
  assert.equal(report.sumMoney(report.incomeRecords(rows,2025,'USD','cash')),20)
  assert.equal(report.incomeRecords(rows,2026,'USD','accrual').length,0)
  assert.equal(report.sumMoney(report.incomeRecords(rows,2025,'USD','accrual')),200)
})
test('drafts/cancellations never count and currencies are separate',()=>{
  const rows=['DRAFT','CANCELLED','SENT'].map(status=>invoice({status}))
  assert.equal(report.incomeRecords(rows,2025,'USD','accrual').length,1)
  assert.equal(report.incomeRecords(rows,2025,'EUR','accrual').length,0)
  const expenses=[{expense_date:'2026-01-01',currency:'USD',amount:.1,status:'DRAFT'},{expense_date:'2026-02-01',currency:'USD',amount:.2,status:'APPROVED'},{expense_date:'2025-12-31',currency:'USD',amount:10},{expense_date:'2026-01-01',currency:'EUR',amount:10},{expense_date:'2026-01-01',currency:'USD',amount:10,status:'REJECTED'}]
  assert.equal(report.sumMoney(report.expenseRecords(expenses,2026,'USD')),.3)
})
test('reviewed single-filer thresholds and Social Security cap are year specific',()=>{
  assert.equal(report.estimateFederalTax(16100,2026),0)
  assert.equal(report.estimateFederalTax(28500,2026),1240)
  assert.equal(report.estimateFederalTax(28600,2026),1252)
  assert.equal(report.estimateFederalTax(15750+11925,2025),1192.5)
  assert.equal(report.estimateSETax(399,2026),0)
  assert.equal(report.estimateSETax(200000,2026),184500*.124+200000*.029)
  assert.equal(report.estimateSETax(200000,2025),176100*.124+200000*.029)
  assert.throws(()=>report.estimateFederalTax(1,2027))
  assert.throws(()=>report.estimateSETax(NaN,2026))
})
test('estimated tax periods and shifted deadlines use calendar rules',()=>{
  assert.equal(report.taxQuarters(2025)[1].dueDate,'2025-06-16')
  assert.equal(report.taxQuarters(2026)[1].dueDate,'2026-06-15')
  assert.equal(report.taxQuarters(2026)[1].end,'2026-05-31')
  assert.equal(report.taxQuarters(2026)[3].dueDate,'2027-01-15')
  assert.throws(()=>report.taxQuarters(2027))
})
test('production CSP limits scripts to nonces and backend connections to configured origin',()=>{
  const {contentSecurityPolicy:csp}=app('src/lib/content-security-policy.ts')
  const policy=csp('testnonce','https://backend.example.invalid/some/path',false)
  assert.ok(policy.includes("script-src 'self' 'nonce-testnonce' 'strict-dynamic';"))
  assert.ok(!policy.includes('unsafe-eval'))
  assert.ok(policy.includes("connect-src 'self' https://backend.example.invalid wss://backend.example.invalid;"))
  assert.throws(()=>csp("bad'; script-src *",undefined,false))
  assert.throws(()=>csp('test','http://external.example.invalid',false))
  assert.ok(csp('test','http://127.0.0.1:54321',true).includes("'unsafe-eval'"))
})

test('fiscal report boundaries use the start year and include the last day across leap years',()=>{
  assert.deepEqual(JSON.parse(JSON.stringify(report.reportPeriod(2023,3))),{start:'2023-03-01',endExclusive:'2024-03-01',end:'2024-02-29'})
  assert.equal(report.reportPeriod(2025,4).end,'2026-03-31')
  for(const args of [[1999,1],[2026,0],[2026,13],[2026,1.5],[NaN,1]]) assert.throws(()=>report.reportPeriod(...args))
})
test('fiscal cash and issued-income reports use matching expense periods without changing tax quarters',()=>{
  const rows=[invoice({issue_date:'2025-04-01',payments:[{id:'before',paid_on:'2025-03-31',amount:1},{id:'start',paid_on:'2025-04-01',amount:2},{id:'last',paid_on:'2026-03-31',amount:3},{id:'after',paid_on:'2026-04-01',amount:4},{id:'reversed',paid_on:'2026-01-01',amount:5,reversal:{id:'r'}}]})]
  assert.equal(report.sumMoney(report.incomeRecords(rows,2025,'USD','cash',4)),5)
  assert.equal(report.sumMoney(report.incomeRecords(rows,2025,'USD','accrual',4)),100)
  const expenses=['2025-03-31','2025-04-01','2026-03-31T23:59:00Z','2026-04-01'].map(expense_date=>({expense_date,currency:'USD',amount:10,status:'DRAFT'}))
  assert.equal(report.sumMoney(report.expenseRecords(expenses,2025,'USD',4)),20)
  assert.equal(report.taxQuarters(2025)[0].start,'2025-01-01')
})
test('saved display preferences format calendar dates without changing their day or ISO input values',()=>{
  const dates=app('src/lib/date-format.ts')
  assert.equal(dates.formatPreferredDate('2026-01-01T00:00:00Z','MM/DD/YYYY'),'01/01/2026')
  assert.equal(dates.formatPreferredDate('2026-09-25','DD/MM/YYYY'),'25/09/2026')
  assert.equal(dates.formatPreferredDate('2026-09-25','YYYY-MM-DD'),'2026-09-25')
  assert.equal(dates.formatPreferredDate(null,'DD/MM/YYYY'),'-')
  assert.equal(dates.dateInputValue('2026-09-25T00:00:00Z'),'2026-09-25')
  assert.equal(dates.formatPreferredDate('bad','MM/DD/YYYY',true),'-')
  assert.equal(dates.dateFormatPattern('untrusted-pattern'),'MM/dd/yyyy')
})
test('invoice details retain the one-to-one legacy review returned by PostgREST',()=>{
  const {mapInvoice}=app('src/lib/invoice-records.ts')
  const review={id:'review',action:'record_payment',evidence:'Synthetic evidence',original_paid_at:'2025-01-20',original_total:50,original_currency:'USD',created_at:'2026-09-26'}
  assert.equal(mapInvoice({...invoice(),legacy_reviews:review}).legacy_reviews[0].evidence,review.evidence)
  assert.equal(mapInvoice({...invoice(),legacy_reviews:[review]}).legacy_reviews.length,1)
  assert.equal(mapInvoice({...invoice(),legacy_reviews:null}).legacy_reviews.length,0)
})
