async function cookieHeader(actor) {
  const jar = new Map()
  const client = createServerClient(s.API_URL,s.ANON_KEY,{ cookies: { getAll:()=>[...jar].map(([name,value])=>({name,value})),setAll:values=>values.forEach(({name,value})=>jar.set(name,value)) } })
  const { data: { session } } = await actor.client.auth.getSession()
  await ok(client.auth.setSession(session),'prepare server cookie session')
  return [...jar].map(([name,value])=>`${name}=${value}`).join('; ')
}
