async function account(type) {
  const email = `release-${randomUUID()}@example.invalid`
  const password = randomBytes(24).toString('base64url')
  const { user } = await ok(admin.auth.admin.createUser({ email, password, email_confirm: true, user_metadata: { name: 'Synthetic release test' } }), 'create local auth fixture')
  const client = createClient(s.API_URL, s.ANON_KEY, options); clients.push(client)
  await ok(client.auth.signInWithPassword({ email, password }), 'sign in')
  const profileApi = services(client)('src/services/profile.service.ts')
  await Promise.all([profileApi.ensureOwnProfile(user, type), profileApi.ensureOwnProfile(user, type)])
  await ok(client.rpc('set_own_account_type', { account_type_param: type }), 'choose account type')
  let org
  if (type === 'business') {
    org = await ok(client.from('organizations').insert({ name: 'Synthetic release workspace' }).select().single(), 'create own organization')
    await ok(client.from('users').update({ organization_id: org.id, role: 'OWNER' }).eq('id', user.id), 'join owned organization')
  }
  const profile = await ok(client.from('users').select('*').eq('id', user.id).single(), 'load onboarded profile')
  assert.equal(profile.account_type, type); assert.equal(profile.is_active, true)
  return { client, user, org, email, password }
}
